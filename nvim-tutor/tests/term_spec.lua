local term = require("tutor.term")

local function new()
  -- `cat` echoes what we send; it stays alive until the job is killed.
  return term.new({ cmd = { "cat" }, cwd = vim.fn.getcwd(), width = 0.4 })
end

describe("tutor.term", function()
  it("starts the job on first show and keeps it across hide/show", function()
    local t = new()
    assert.is_false(t:is_visible())
    t:show()
    assert.is_true(t:is_visible())
    local job = t:job_id()
    assert.is_number(job)
    assert.is_true(t:is_running())
    t:hide()
    assert.is_false(t:is_visible())
    assert.is_true(t:is_running())
    t:show()
    assert.equals(job, t:job_id())
    t:hide()
  end)

  it("send writes text plus carriage return into the job", function()
    local t = new()
    t:show()
    t:send("hello")
    vim.wait(1000, function()
      local lines = vim.api.nvim_buf_get_lines(t:bufnr(), 0, -1, false)
      return vim.tbl_contains(lines, "hello")
    end)
    local lines = vim.api.nvim_buf_get_lines(t:bufnr(), 0, -1, false)
    assert.is_true(vim.tbl_contains(lines, "hello"))
    t:hide()
  end)

  it("restart replaces the job id", function()
    local t = new()
    t:show()
    local job = t:job_id()
    t:restart()
    vim.wait(500, function() return t:job_id() ~= job end)
    assert.is_not.equals(job, t:job_id())
    assert.is_true(t:is_running())
    t:hide()
  end)

  it("sizes the split to the requested fraction of columns", function()
    local t = new()
    t:show()
    local want = math.floor(vim.o.columns * 0.4)
    local got = vim.api.nvim_win_get_width(t.win)
    assert.is_true(math.abs(got - want) <= 1)
    t:hide()
  end)

  it("passes opts.env to the job", function()
    local t = term.new({ cmd = { "sh", "-c", 'printf "T=%s\\n" "$PI_TUTOR"; cat' }, cwd = vim.fn.getcwd(), width = 0.4, env = { PI_TUTOR = "1" } })
    t:show()
    local ok = vim.wait(2000, function()
      return vim.tbl_contains(vim.api.nvim_buf_get_lines(t:bufnr(), 0, -1, false), "T=1")
    end)
    assert.is_true(ok)
    t:hide()
  end)
end)

describe("tutor.term restart (review fixes)", function()
  local function new()
    return require("tutor.term").new({ cmd = { "cat" }, cwd = vim.fn.getcwd(), width = 0.4 })
  end
  local function term_bufs()
    local n = 0
    for _, b in ipairs(vim.api.nvim_list_bufs()) do
      if vim.api.nvim_buf_is_loaded(b) and vim.bo[b].buftype == "terminal" then n = n + 1 end
    end
    return n
  end

  it("restart from the editor window does not hijack the editor buffer (C1)", function()
    local t = new()
    t:show()
    vim.cmd("wincmd h")
    local editor_buf = vim.api.nvim_get_current_buf()
    t:restart()
    assert.equals(editor_buf, vim.api.nvim_get_current_buf())
    assert.is_not.equals("terminal", vim.bo[editor_buf].buftype)
    assert.equals("terminal", vim.bo[t:bufnr()].buftype)
    assert.equals(t:bufnr(), vim.api.nvim_win_get_buf(t.win))
    t:hide()
  end)

  it("stays running after the old job's exit callback fires (I2)", function()
    local t = new()
    t:show()
    t:restart()
    vim.wait(500)
    assert.is_true(t:is_running())
    assert.is_number(t:job_id())
    assert.is_true(t:send("ping"))
    t:hide()
  end)

  it("restart before the pane was ever opened starts exactly one job (I3)", function()
    local before = term_bufs()
    local t = new()
    t:restart()
    vim.wait(200)
    assert.equals(before + 1, term_bufs())
    t:hide()
  end)
end)

describe("tutor.term pane review (M6c final)", function()
  local function new(cmd)
    return require("tutor.term").new({ cmd = cmd or { "cat" }, cwd = vim.fn.getcwd(), width = 0.4 })
  end
  --- Run fn inside an <expr> mapping, where textlock forbids window changes (E565).
  local function under_textlock(fn)
    vim.keymap.set("n", "<F13>", function() fn(); return "" end, { expr = true })
    vim.api.nvim_feedkeys(vim.keycode("<F13>"), "x", false)
    vim.keymap.del("n", "<F13>")
  end

  it("a pi that cannot start leaves no dead pane and says so (pane #2)", function()
    local wins = #vim.api.nvim_tabpage_list_wins(0)
    local msgs = {}
    local orig = vim.notify
    vim.notify = function(m) table.insert(msgs, m) end
    local t = new({ "/nonexistent/no-such-pi" })
    local ok = pcall(function() t:show() end)
    vim.notify = orig
    assert.is_true(ok)
    assert.is_false(t:is_visible())
    assert.is_nil(t:bufnr())
    assert.is_false(t:is_running())
    assert.equals(wins, #vim.api.nvim_tabpage_list_wins(0))
    assert.is_truthy(msgs[1] and msgs[1]:find("could not start"))
  end)

  it("show, hide and restart under textlock retry on the event loop (pane #3)", function()
    local t = new()
    vim.v.errmsg = ""
    under_textlock(function() t:show() end)
    assert.is_true(vim.wait(1000, function() return t:is_visible() and t:is_running() end))
    under_textlock(function() t:hide() end)
    assert.is_true(vim.wait(1000, function() return not t:is_visible() end))
    local job = t:job_id()
    under_textlock(function() t:restart() end)
    assert.is_true(vim.wait(1000, function() return t:is_running() and t:job_id() ~= job end))
    assert.is_nil(vim.v.errmsg:find("E565"))
    t:close()
  end)

  it("the old job's exit code does not land on the restarted pane (pane #9)", function()
    local t = new()
    t:show()
    local old = t:bufnr()
    t:restart()
    vim.wait(500)
    assert.are_not.equal(old, t:bufnr())
    assert.is_nil(vim.b[t:bufnr()].tutor_exit_code)
    t:close()
  end)
end)

-- Last: `:only` changes the window layout the other tests rely on.
describe("tutor.term minors (M6c)", function()
  it("hiding the pane when it is the only window does not raise E444 (M1b #1)", function()
    local t = new()
    t:show()
    vim.cmd("only")
    assert.has_no.errors(function() t:hide() end)
    assert.is_false(t:is_visible())
    assert.is_true(t:is_running())
    assert.are_not.equal("terminal", vim.bo[vim.api.nvim_get_current_buf()].buftype)
  end)

  it("close stops the job and wipes the buffer (M1b #8)", function()
    local t = new()
    t:show()
    local buf = t:bufnr()
    t:close()
    assert.is_false(t:is_running())
    assert.is_false(vim.api.nvim_buf_is_valid(buf))
  end)
end)
