local panel = require("tutor.panel")

describe("panel", function()
  it("appends user text and streams a reply into one assistant block", function()
    local p = panel.new({ on_submit = function() end })
    p:append_user("hello")
    p:append_delta("Hel")
    p:append_delta("lo\nworld")
    p:end_reply()
    assert.same({ "> hello", "", "Hello", "world", "" }, p:lines())
  end)

  it("renders the status line from fields", function()
    local p = panel.new({ on_submit = function() end })
    p:set_status({ language = "rust", level = 42, rung = 2, task = "P1.T2.S3", state = "idle" })
    assert.equals("rust · lvl 42 · rung 2 · P1.T2.S3 · idle", p:status_line())
  end)

  it("leaves no waiting state after a handled prompt", function()
    local p = panel.new({ on_submit = function() end })
    p:set_status({ state = "waiting" })
    p:end_reply()
    assert.equals("idle", p.status.state)
  end)

  it("calls on_submit with the input text and ignores blank input", function()
    local got
    local p = panel.new({ on_submit = function(t) got = t end })
    p:submit("   ")
    assert.is_nil(got)
    p:submit("what is a trait")
    assert.equals("what is a trait", got)
  end)

  it("toggles a split window open and closed", function()
    local p = panel.new({ on_submit = function() end })
    assert.is_false(p:is_open())
    p:toggle()
    assert.is_true(p:is_open())
    p:toggle()
    assert.is_false(p:is_open())
  end)
end)

describe("panel window (review fixes)", function()
  it("shows the chat buffer in the split and survives appends while open (C1)", function()
    local p = panel.new({ on_submit = function() end })
    p:append_user("one")
    p:append_user("two")
    p:toggle()
    assert.equals(p.chat_buf, vim.api.nvim_win_get_buf(p.split.winid))
    p:append_user("three")
    p:append_delta("reply")
    p:end_reply()
    assert.equals(#p:lines(), vim.api.nvim_buf_line_count(p.chat_buf))
    p:toggle()
    assert.is_true(vim.api.nvim_buf_is_valid(p.chat_buf))
    p:toggle()
    assert.equals("> three", p:lines()[5])
    p:toggle()
  end)

  it("keeps the panel open with a live input after a submit (I1)", function()
    local got
    local p = panel.new({ on_submit = function(t) got = t end })
    p:toggle()
    p:_on_input_submit("hi")
    assert.equals("hi", got)
    assert.is_true(p:is_open())
    assert.is_not_nil(p.input)
    assert.is_true(vim.api.nvim_win_is_valid(p.input.winid))
    p:toggle()
  end)
end)
